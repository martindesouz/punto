// Generates api/_lib/allowed-words.ts from the `word-list` package (MIT).
// Run once after `npm install`: node scripts/build-allowed-words.mjs
// The output file is committed so production builds don't need word-list.
import { readFileSync, writeFileSync } from 'node:fs'
import wordListPath from 'word-list'

const words = readFileSync(wordListPath, 'utf8')
  .split('\n')
  .filter(w => /^[a-z]{5}$/.test(w))

const out = `// Auto-generated by scripts/build-allowed-words.mjs — do not edit.
// ${words.length} five-letter words from the word-list package (MIT).
const RAW = '${words.join(' ')}'
export const ALLOWED_WORDS: ReadonlySet<string> = new Set(RAW.split(' '))
`
writeFileSync(new URL('../api/_lib/allowed-words.ts', import.meta.url), out)
console.log(`Wrote ${words.length} words to api/_lib/allowed-words.ts`)
